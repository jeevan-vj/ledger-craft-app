import { test, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';

// Disposable local Better Auth + SQLite only. No production data or sessions.
test('sender explicitly replaces expiry and snapshot; recipients lose old links', async ({ browser, baseURL }) => {
  if (!baseURL || !/^http:\/\/(localhost|127\.0\.0\.1):/.test(baseURL)) throw new Error('Use a local test server');
  const artifacts = '/tmp/ledgercraft-verify-sharing-controls';
  await mkdir(artifacts, { recursive: true });
  const owner = await browser.newContext({ baseURL, viewport: { width: 1440, height: 900 } });
  const recipient = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 } });
  const send = async (path: string, data: unknown, method = 'POST') => {
    const response = await owner.request.fetch(`/api/${path}`, { method, headers: { Origin: baseURL }, data });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.json();
  };
  try {
    await send('auth/sign-up/email', { name: 'Share controls QA', email: `controls-${Date.now()}@example.com`, password: 'Local-sharing-test-123!' });
    const profile = { name: 'Original Studio', email: 'studio@example.com', country: 'NZ', defaultTaxRate: '15' };
    await send('business-profile', profile, 'PUT');
    const customer = await send('customers', { name: 'Sharing Customer', email: 'customer@example.com', country: 'NZ' });
    const invoice = await send('invoices', { customerId: customer.id, date: '2026-10-25', dueDate: '2026-11-25', taxRate: '15', taxInclusive: false, notes: 'Original snapshot notes', items: [{ description: 'Design work', quantity: '1', rate: '100' }] });
    const page = await owner.newPage();
    await page.goto('/invoices');
    await page.evaluate(() => document.querySelector<HTMLButtonElement>('[aria-label="Dismiss update prompt"]')?.click());
    await page.getByRole('button', { name: 'Share invoice', exact: true }).first().click();
    await expect(page.getByText('No active link for this template.')).toBeVisible();
    await page.getByRole('button', { name: 'Generate Share Link', exact: true }).click();
    await expect(page.getByText('Active link · No expiry', { exact: true })).toBeVisible();
    const link = page.getByLabel('Share Link', { exact: true });
    const originalUrl = await link.inputValue();
    const oldToken = originalUrl.split('/').pop();
    await send(`invoices/${invoice.id}`, { notes: 'Fresh snapshot notes' }, 'PATCH');
    await send('business-profile', { ...profile, name: 'Updated Studio' }, 'PUT');
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    await page.getByRole('button', { name: 'Share invoice', exact: true }).first().click();
    await expect(link).toHaveValue(originalUrl);
    const original = await recipient.request.get(`/api/public/invoices/${oldToken}`);
    expect((await original.json()).invoice.notes).toBe('Original snapshot notes');
    await page.getByRole('switch', { name: 'Link Expiration' }).click();
    await page.getByLabel('Expires in (days)').fill('1');
    await expect(page.getByText('Active link · No expiry', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Replace link', exact: true }).click();
    await page.getByRole('button', { name: 'Keep existing links' }).click();
    await expect(link).toHaveValue(originalUrl);
    await page.getByRole('button', { name: 'Replace link', exact: true }).click();
    await page.getByRole('button', { name: 'Replace and invalidate old links' }).click();
    await expect(link).not.toHaveValue(originalUrl);
    await expect(page.getByText(/^Active link · Expires /)).toBeVisible();
    const freshUrl = await link.inputValue();
    const listed = await (await owner.request.get(`/api/invoices/${invoice.id}/shares`)).json();
    expect(listed.shares).toHaveLength(1);
    const expiry = listed.shares[0].expiresAt;
    expect(Date.parse(expiry) - Date.now()).toBeGreaterThan(86_000_000);
    expect(Date.parse(expiry) - Date.now()).toBeLessThanOrEqual(86_400_000);
    await expect(page.getByText(`Active link · Expires ${new Date(expiry).toLocaleString()}`, { exact: true })).toBeVisible();
    await page.evaluate(() => document.querySelectorAll<HTMLButtonElement>('[toast-close]').forEach(button => button.click()));
    await expect(page.getByText('Share link replaced', { exact: true })).not.toBeVisible();
    await page.screenshot({ path: `${artifacts}/1440.png`, mask: [link], maskColor: '#64748b', animations: 'disabled' });
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Share invoice', exact: true }).first().click();
    await expect(page.getByRole('button', { name: 'Replace link', exact: true })).toBeInViewport();
    await page.screenshot({ path: `${artifacts}/390.png`, mask: [link], maskColor: '#64748b', animations: 'disabled' });
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    await page.screenshot({ path: `${artifacts}/390-dark.png`, mask: [link], maskColor: '#64748b', animations: 'disabled' });
    expect((await recipient.request.get('/api/me')).status()).toBe(401);
    const recipientPage = await recipient.newPage();
    await recipientPage.goto(originalUrl);
    await expect(recipientPage.getByText('This link is no longer active', { exact: true })).toBeVisible();
    await recipientPage.screenshot({ path: `${artifacts}/recipient-inactive.png` });
    await recipientPage.goto(freshUrl);
    await expect(recipientPage.getByText('Fresh snapshot notes', { exact: true })).toBeVisible();
    await expect(recipientPage.getByText('Updated Studio', { exact: true }).first()).toBeVisible();
    const fresh = await recipient.request.get(`/api/public/invoices/${freshUrl.split('/').pop()}`);
    expect((await fresh.json()).invoice.total).toBe('115.00');
    await recipientPage.evaluate(() => document.querySelector<HTMLButtonElement>('[aria-label="Dismiss update prompt"]')?.click());
    await recipientPage.screenshot({ path: `${artifacts}/02-preview.png`, fullPage: true });
    const downloadReady = recipientPage.waitForEvent('download');
    await recipientPage.getByRole('button', { name: 'Download PDF', exact: true }).click();
    const download = await downloadReady;
    expect(download.suggestedFilename()).toBe(`Invoice-${invoice.invoiceNumber}.pdf`);
    const pdfPath = `${artifacts}/${download.suggestedFilename()}`;
    await download.saveAs(pdfPath);
    const pdf = await readFile(pdfPath);
    expect(pdf.subarray(0, 5).toString()).toBe('%PDF-');
    expect(pdf.length).toBeGreaterThan(1024);
    await send(`invoices/${invoice.id}/shares/revoke`, {});
    await recipientPage.reload();
    await expect(recipientPage.getByText('This link is no longer active', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    await page.route('**/api/invoices/*/shares', route => route.abort());
    await page.getByRole('button', { name: 'Share invoice', exact: true }).first().click();
    await expect(page.getByText('Could not load the current links.')).toBeVisible();
    await page.screenshot({ path: `${artifacts}/390-error.png` });
    await page.unroute('**/api/invoices/*/shares');
    await page.getByRole('button', { name: 'Retry loading links' }).click();
    await expect(page.getByText('No active link for this template.')).toBeVisible();
    await page.getByRole('button', { name: 'Generate Share Link', exact: true }).click();
    await expect(page.getByText('Active link · No expiry', { exact: true })).toBeVisible();
  } finally {
    await owner.close();
    await recipient.close();
  }
});
