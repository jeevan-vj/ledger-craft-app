import { generateGstPeriods, type CreateTaxReturnRequest, type GstCalculationSnapshot, type GstPreparationResponse, type GstSettingsDto, type TaxReturnDto } from '@ledgercraft/contracts';
import type { Database } from '../../db/client';
import { apiError } from '../../http-error';
import { decimal } from '../invoices/money';
import { gstSettingsInTx } from './gst-settings';
import { gstPreparationInTx, reviewedGstPreparationInTx } from './gst-preparation';
import { buildGstCalculationSnapshot, stableGstFingerprint } from './gst-calculation';
import * as repo from './tax.repository';

type Context = { organisationId: string; userId: string };
const fields = ['totalSales', 'totalPurchases', 'gstOnSales', 'gstOnPurchases', 'netGst'] as const;
function snapshotContent(snapshot: GstCalculationSnapshot) {
  const { calculatedAt: _calculatedAt, ...content } = snapshot;
  return content;
}

export async function assertNoFiledGstOverlap(tx: Database, organisationId: string, from: string, to: string, exceptId?: string) {
  const overlap = (await repo.listReturns(tx, organisationId)).some(row => row.id !== exceptId && row.returnType === 'GST'
    && ['submitted', 'approved'].includes(row.status) && !row.supersededAt && row.periodStart <= to && row.periodEnd >= from);
  if (overlap) throw apiError(409, 'GST_PERIOD_ALREADY_FILED', 'This period overlaps a recorded filed GST return. Prepare a separate correction rather than a duplicate filing.');
}

export async function preparationForStoredGst(tx: Database, ctx: Context, row: TaxReturnDto): Promise<GstPreparationResponse> {
  const original = row.returnData?.gstCalculation;
  if (!original) throw apiError(409, 'GST_SNAPSHOT_REQUIRED', 'This legacy GST record has no authoritative source snapshot. Review and prepare a new calculation; the recorded return has not been changed.');
  const review = row.returnData?.gstReview;
  const options = { settingsOverride: original.settings, allowStaleClassificationReview: true };
  const period = { from: row.periodStart, to: row.periodEnd, basis: original.period.basis };
  return review
    ? reviewedGstPreparationInTx(tx, ctx, { ...period, reviewConfirmed: true, adjustments: review.adjustments, salesClassificationReview: review.salesClassificationReview }, options)
    : gstPreparationInTx(tx, ctx, period, options);
}

/** Client totals are assertions, not inputs to the tax calculation. All reads,
 * review arithmetic and the eventual return write share one organisation tx. */
export async function canonicalGstReturnInput(tx: Database, ctx: Context, input: CreateTaxReturnRequest): Promise<CreateTaxReturnRequest> {
  const settings = await gstSettingsInTx(tx, ctx.organisationId);
  if (!settings.configured || settings.gstRegistrationStatus !== 'registered') {
    throw apiError(422, 'GST_SETTINGS_REQUIRED', 'Confirm the registered New Zealand business GST number, registration date, accounting basis, frequency and period anchor before saving a GST return.');
  }
  const selected = generateGstPeriods(settings, input.periodEnd).find(period => period.periodStart === input.periodStart && period.periodEnd === input.periodEnd);
  if (!selected) throw apiError(422, 'GST_PERIOD_MISMATCH', 'Choose a GST period generated from the saved IRD registration settings.');
  if (input.returnData?.preparation?.basis && input.returnData.preparation.basis !== settings.gstAccountingBasis) {
    throw apiError(409, 'GST_SETTINGS_CHANGED', 'GST settings changed. Recalculate this return using the saved accounting basis.');
  }
  if (input.returnData?.preparation?.dueDate && input.returnData.preparation.dueDate !== selected.dueDate) {
    throw apiError(422, 'GST_DUE_DATE_MISMATCH', 'Use the generated GST due date and confirm any IRD extension separately.');
  }
  const period = { from: input.periodStart, to: input.periodEnd, basis: settings.gstAccountingBasis! };
  const review = input.returnData?.gstReview;
  const preparation = review
    ? await reviewedGstPreparationInTx(tx, ctx, { ...period, reviewConfirmed: true, adjustments: review.adjustments, salesClassificationReview: review.salesClassificationReview })
    : await gstPreparationInTx(tx, ctx, period);
  const calculation = preparation.calculation ?? await buildGstCalculationSnapshot(tx, ctx, preparation, settings);
  for (const fingerprint of [input.returnData?.preparation?.calculationFingerprint, input.returnData?.gstCalculation?.fingerprint]) {
    if (fingerprint && fingerprint !== calculation.fingerprint) throw apiError(409, 'GST_CALCULATION_STALE', 'The books or GST settings changed. Recalculate and review the current figures before saving.');
  }
  if (input.returnData?.gstCalculation && stableGstFingerprint(snapshotContent(input.returnData.gstCalculation)) !== stableGstFingerprint(snapshotContent(calculation))) {
    throw apiError(422, 'GST_SNAPSHOT_OVERRIDE', 'Calculation snapshots are generated by the server and cannot be overridden.');
  }
  if (calculation.requiresReview && !review?.confirmed) {
    throw apiError(422, 'GST_REVIEW_REQUIRED', 'Review the calculation warnings and supported source classifications before saving this GST draft.');
  }
  const figures = { totalSales: preparation.totalSales, totalPurchases: preparation.totalPurchases, gstOnSales: preparation.gstOnSales, gstOnPurchases: preparation.gstOnPurchases, netGst: preparation.netGstPosition };
  if (fields.some(field => decimal(input[field]).compare(figures[field]) !== 0)) {
    throw apiError(422, 'GST_FIGURES_MISMATCH', 'GST figures must match the current server calculation. Client totals cannot override the books.');
  }
  return { ...input, ...figures, returnType: 'GST', returnData: {
    preparation: { basis: preparation.basis, baseCurrency: 'NZD', dueDate: selected.dueDate, calculationFingerprint: calculation.fingerprint },
    gstCalculation: calculation,
    ...(preparation.review ? { gstReview: preparation.review } : {}),
    ...(input.returnData?.reconciliation ? { reconciliation: input.returnData.reconciliation } : {}),
  } };
}
